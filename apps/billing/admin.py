from django.contrib import admin, messages
from django.utils.html import format_html
from .models import Plan, Subscription, UsageAuditLog

@admin.register(Plan)
class PlanAdmin(admin.ModelAdmin):
    list_display = ('name', 'tier', 'monthly_request_quota', 'price_inr', 'allows_auto_captcha', 'allows_deep_scrape')
    list_filter = ('tier', 'allows_auto_captcha', 'allows_deep_scrape')
    search_fields = ('name',)


@admin.register(Subscription)
class SubscriptionAdmin(admin.ModelAdmin):
    list_display = ('user', 'plan', 'usage_meter', 'is_active', 'billing_cycle_anchor')
    list_filter = ('plan', 'is_active')
    search_fields = ('user__username', 'user__email', 'notes')
    actions = ['reset_monthly_usage_action', 'activate_subscriptions', 'deactivate_subscriptions']

    def usage_meter(self, obj):
        quota = obj.plan.monthly_request_quota
        used = obj.current_month_usage
        pct = min(100, int((used / quota) * 100)) if quota > 0 else 0
        color = "#10B981" if pct < 75 else ("#F59E0B" if pct < 90 else "#EF4444")
        return format_html(
            "<div style='width:120px; background:#e5e7eb; border-radius:4px; overflow:hidden;'>"
            "<div style='width:{}%; background:{}; height:14px; text-align:center; color:#fff; font-size:10px; line-height:14px;'>"
            "{} / {}"
            "</div></div>",
            pct, color, used, quota
        )
    usage_meter.short_description = "Usage / Quota"

    def reset_monthly_usage_action(self, request, queryset):
        for sub in queryset:
            sub.reset_usage()
        messages.success(request, f"Successfully reset usage count to 0 for {queryset.count()} subscription(s).")
    reset_monthly_usage_action.short_description = "Reset monthly usage count to 0"

    def activate_subscriptions(self, request, queryset):
        queryset.update(is_active=True)
        messages.success(request, f"Activated {queryset.count()} subscription(s).")
    activate_subscriptions.short_description = "Activate selected subscriptions"

    def deactivate_subscriptions(self, request, queryset):
        queryset.update(is_active=False)
        messages.warning(request, f"Deactivated {queryset.count()} subscription(s).")
    deactivate_subscriptions.short_description = "Deactivate selected subscriptions"


@admin.register(UsageAuditLog)
class UsageAuditLogAdmin(admin.ModelAdmin):
    list_display = ('timestamp', 'user', 'school_code', 'session_year', 'class_name', 'students_extracted', 'execution_time_seconds', 'status')
    list_filter = ('status', 'timestamp')
    search_fields = ('school_code', 'user__username', 'class_name')
    readonly_fields = [f.name for f in UsageAuditLog._meta.fields]

    def has_add_permission(self, request):
        return False  # Audit logs can only be generated by the API engine

    def has_change_permission(self, request, obj=None):
        return False
